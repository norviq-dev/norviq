"""The FOSSA job must fail when fossa-cli would read less of the Python closure than the file holds.

fossa.yml asserts the setuptools project "succeeded", and it succeeds with zero dependencies: the
requirements parser in fossa-cli (src/Strategy/Python/ReqTxt.hs) drops any line it cannot parse. The
grep checks in the same step look for `^fastapi` and pass the line whether the parser can read it or
not. These tests hold scripts/check_fossa_requirements.py to the parser's grammar, and run it on the
real export.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_ROOT / "scripts"))

from check_fossa_requirements import check, is_discovered, requirement_name  # noqa: E402


def _must() -> list[str]:
    """The packages fossa.yml requires in the export, read from its MUST list."""
    m = re.search(r'MUST="([^"]+)"', (_ROOT / ".github/workflows/fossa.yml").read_text())
    assert m, "fossa.yml no longer names the packages the export must contain"
    return m.group(1).split()


def _target(tmp_path: Path, text: str, name: str = "requirements-runtime.txt") -> Path:
    (tmp_path / name).write_text(text)
    return tmp_path


@pytest.mark.parametrize(
    "line",
    [
        "fastapi==0.139.0",
        "fastapi==0.139.0 ; python_full_version < '3.14'",
        "async-timeout==5.0.1 ; python_full_version < '3.11.3'",
        "numpy==2.5.1 ; python_full_version >= '3.12' and python_full_version < '3.14'",
        "cffi==2.0.0 ; python_full_version < '3.14' and implementation_name != 'PyPy' "
        "and platform_python_implementation != 'PyPy'",
        "colorama==0.4.6 ; (python_full_version < '3.14' and os_name == 'nt') "
        "or (python_full_version < '3.14' and sys_platform == 'win32')",
        "redis[hiredis]==7.0.1",
        "zope.interface==8.0",
    ],
)
def test_every_shape_uv_writes_is_read(line: str) -> None:
    """Each marker shape here occurs in an export of this lock."""
    assert requirement_name(line) is not None, line


@pytest.mark.parametrize(
    "line",
    [
        # Util.hs's env_var list has no dotted legacy names; the marker fails and takes the line with it.
        "fastapi==0.139.0 ; sys.platform == 'linux'",
        # Unpinned: FOSSA would grade a range, not the version the lock resolved.
        "fastapi>=0.109",
        # Forms this check does not vouch for, whatever fossa-cli makes of them.
        "fastapi==0.139.0 ; python_version in '3.11 3.12 3.13'",
        "fastapi==0.139.0 ; (python_full_version < '3.14' )",
        "    fastapi==0.139.0",
        "fastapi==0.139.0 \\",
        "fastapi @ https://example.invalid/fastapi-0.139.0.tar.gz",
        "-e .",
    ],
)
def test_a_line_outside_the_vouched_grammar_is_not_read(line: str) -> None:
    assert requirement_name(line) is None, line


def test_the_grep_check_passes_a_line_this_check_refuses(tmp_path: Path) -> None:
    """The reason this check exists beside the grep: `^fastapi([=<>[;]|$)` matches the line, so the
    must-list loop passes, and nothing says whether fossa-cli reads it."""
    line = "fastapi==0.139.0 ; python_version in '3.11 3.12 3.13'"
    assert subprocess.run(["grep", "-qiE", "^fastapi([=<>[;]|$)"], input=line, text=True).returncode == 0
    code, msg = check(_target(tmp_path, f"pydantic==2.12.0\n{line}\n"), ["fastapi"])
    assert code == 1 and "requirements-runtime.txt:2" in msg


def test_comments_and_blank_lines_are_skipped(tmp_path: Path) -> None:
    text = (
        "# This file was autogenerated by uv via the following command:\n"
        "#    uv export --frozen --no-dev --extra spiffe --no-emit-project --no-hashes\n"
        "fastapi==0.139.0 ; python_full_version < '3.14'\n"
        "    # via norviq\n"
        "\n"
    )
    code, msg = check(_target(tmp_path, text), ["fastapi"])
    assert code == 0 and "1 pinned requirement" in msg, msg


def test_an_empty_export_fails(tmp_path: Path) -> None:
    code, msg = check(_target(tmp_path, "# This file was autogenerated by uv\n"), [])
    assert code == 1 and "no package" in msg


def test_a_missing_required_package_fails(tmp_path: Path) -> None:
    code, msg = check(_target(tmp_path, "pydantic==2.12.0\n"), ["fastapi", "pydantic"])
    assert code == 1 and "fastapi" in msg


def test_names_compare_the_way_pypi_does(tmp_path: Path) -> None:
    assert check(_target(tmp_path, "Typing_Extensions==4.15.0\n"), ["typing-extensions"])[0] == 0


def test_no_discovered_file_fails(tmp_path: Path) -> None:
    code, msg = check(_target(tmp_path, "fastapi==0.139.0\n", name="deps.txt"), ["fastapi"])
    assert code == 1 and "discovered" in msg


def test_discovery_follows_fossa_cli_not_a_glob(tmp_path: Path) -> None:
    """Setuptools.hs reads every `*req*.txt`, so a second file is read and checked too."""
    assert is_discovered("dev-requirements.txt") and is_discovered("requirements-runtime.txt")
    assert not is_discovered("Requirements.txt") and not is_discovered("requirements.in")
    _target(tmp_path, "fastapi==0.139.0\n")
    code, msg = check(_target(tmp_path, "pytest>=8\n", name="dev-requirements.txt"), ["fastapi"])
    assert code == 1 and "dev-requirements.txt:1" in msg


def _uv() -> str:
    uv = shutil.which("uv")
    if uv is None:
        pytest.skip("uv is not on PATH")
    return uv


@pytest.mark.parametrize("extra", ["spiffe", "frameworks"])
def test_the_real_export_is_read_in_full(tmp_path: Path, extra: str) -> None:
    """`spiffe` is what fossa.yml exports. Between them, these two exports hold every marker shape that
    any export of this lock has (checked on 2026-10-30 across all nine extras)."""
    out = subprocess.run(
        [_uv(), "export", "--frozen", "--no-dev", "--extra", extra, "--no-emit-project", "--no-hashes"],
        cwd=_ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    declared = tomllib.loads((_ROOT / "pyproject.toml").read_text())["project"]["optional-dependencies"]
    assert extra in declared
    code, msg = check(_target(tmp_path, out), _must() if extra == "spiffe" else ["fastapi"])
    assert code == 0, msg
