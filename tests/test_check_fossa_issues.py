VULN = {"type": "vulnerability", "revisionId": "pip+foo$1.0", "cve": "CVE-2099-0001"}
EXCEPTED = {"type": "vulnerability", "revisionId": "pip+litellm$1.100.4", "cve": "CVE-2024-6825"}


def test_one_vulnerability_fails_the_gate():
    code, msg = gate({"issues": [VULN]})
    assert code == 1 and "FAILED" in msg and "CVE-2099-0001" in msg


def test_a_documented_exception_passes_and_is_reported():
    code, msg = gate({"issues": [EXCEPTED]})
    assert code == 0 and "1 accepted" in msg


def test_capitalised_key_and_bare_list_are_read_not_ignored():
    assert gate({"Issues": [VULN]})[0] == 1
    assert gate([VULN])[0] == 1


@pytest.mark.parametrize("payload", [{}, {"summary": "ok"}, {"issues": None}, {"issues": "none"}, "ok", 42])
def test_an_unrecognised_shape_is_refused_not_passed(payload):
    """`{}` used to produce an empty list, zero findings, and PASS."""
    with pytest.raises(UnrecognisedShape):
        issues_from(payload)


def test_genuinely_empty_is_the_only_way_to_pass_clean():
    assert gate({"issues": []})[0] == 0


def test_the_k8s_module_matches_are_excepted_because_they_are_spurious():
    """FOSSA flags three CVEs against k8s.io/{apimachinery,client-go} at any v0.x. Their fixed
    versions (0.17.0, 0.19.6, and kubernetes 1.12.3 — not a library at all) are all far below the
    pinned v0.37.0. If one of these is ever removed from ACCEPTED, the removal should be because the
    advisory data changed, not because someone assumed a bump would clear it — it cannot."""
    for cve in ("CVE-2018-1002105", "CVE-2019-11250", "CVE-2020-8565"):
        code, msg = gate(
            {"issues": [{"type": "vulnerability", "revisionId": "go+k8s.io/client-go$v0.37.0", "cve": cve}]}
        )
        assert code == 0 and "accepted" in msg, cve


_ADVISORY_ID = re.compile(r"CVE-\d{4}-\d{4,}|GHSA(?:-[0-9a-z]{4}){3}")


def _security_md_exception_ids() -> set[str]:
    """Every advisory id in the FIRST column of SECURITY.md's accepted-exceptions table."""
    text = (_ROOT / "SECURITY.md").read_text()
    section = text.split("## Accepted dependency exceptions", 1)[1].split("\n## ", 1)[0]
    rows = [ln for ln in section.splitlines() if ln.startswith("|")]
    return {i for ln in rows for i in _ADVISORY_ID.findall(ln.split("|")[1])}


def test_the_security_md_table_and_the_allow_list_name_the_same_advisories():
    """SECURITY.md and the gate's allow-list are documented as being in lockstep, and they have not
    always been. The React Router row was once written into the table and never into the allow-list,
    so the gate kept failing on a vulnerability the document had already accepted. The opposite
    direction is worse: an id in the allow-list with no row in the table is an exception nobody wrote
    a reason for."""
    table = _security_md_exception_ids()
    assert table, "no advisory ids found in SECURITY.md's exceptions table; the parser no longer fits it"
    assert table == ACCEPTED, (
        f"in SECURITY.md's table only: {sorted(table - ACCEPTED)}; in ACCEPTED only: {sorted(ACCEPTED - table)}"
    )


# --- the shipped-closure check ------------------------------------------------------------------

SHIPPED_TXT = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-dev --extra spiffe --no-emit-project --no-hashes
cryptography==50.0.0 ; python_full_version < '3.14'
    # via norviq
idna==3.18 ; python_full_version < '3.14'
    # via
    #   anyio
    #   httpx
urllib3==2.8.0 ; python_full_version < '3.14'
Typing_Extensions==4.15.0
"""
SHIPPED = shipped_from(SHIPPED_TXT)


def _v(rev: str, cve: str = "CVE-2099-0002", type_: str = "vulnerability") -> dict:
    return {"type": type_, "revisionId": rev, "cve": cve}


def test_the_closure_parser_reads_names_versions_and_normalises():
    assert SHIPPED["cryptography"] == {"50.0.0"} and SHIPPED["typing-extensions"] == {"4.15.0"}


def test_a_vulnerability_at_the_shipped_version_fails():
    code, msg = gate({"issues": [_v("pip+cryptography$50.0.0")]}, SHIPPED)
    assert code == 1 and "FAILED" in msg and "cryptography$50.0.0" in msg


def test_a_vulnerability_at_a_version_that_does_not_ship_is_reported_and_passes():
    code, msg = gate({"issues": [_v("pip+cryptography$46.0.5"), _v("pip+chardet$5.2.0")]}, SHIPPED)
    assert code == 0 and "PASSED" in msg
    assert "not in the shipped closure (FOSSA resolved these itself)" in msg
    assert "FOSSA 46.0.5, shipped 50.0.0" in msg  # both versions, for a package that does ship
    assert "chardet$5.2.0" in msg and "package not shipped" in msg


def test_control_without_the_closure_the_same_finding_fails():
    """The filtering is what makes the previous test pass: without it the finding is gated."""
    code, msg = gate({"issues": [_v("pip+cryptography$46.0.5")]})
    assert code == 1 and "FAILED" in msg


def test_a_mixed_list_fails_if_any_shipped_version_is_vulnerable():
    code, msg = gate({"issues": [_v("pip+cryptography$46.0.5"), _v("pip+idna$3.18", "CVE-2099-0003")]}, SHIPPED)
    assert code == 1 and "CVE-2099-0003" in msg and "FOSSA 46.0.5, shipped 50.0.0" in msg


def test_malware_always_fails_even_outside_the_closure():
    code, msg = gate({"issues": [_v("pip+chardet$5.2.0", None, "malware")]}, SHIPPED)
    assert code == 1 and "malware" in msg


def test_npm_and_go_findings_are_gated_as_before():
    assert gate({"issues": [_v("npm+marked$14.0.0")]}, SHIPPED)[0] == 1
    assert gate({"issues": [_v("go+golang.org/x/text$v0.43.0")]}, SHIPPED)[0] == 1


@pytest.mark.parametrize("text", ["", "# only comments\n", "cryptography>=50\n", "-e .\n"])
def test_an_unreadable_closure_is_refused(text):
    with pytest.raises(UnreadableShipped):
        shipped_from(text)


def test_a_missing_or_unreadable_closure_fails_the_gate_closed(tmp_path, capsys):
    issues = tmp_path / "fossa-issues.json"
    issues.write_text('{"issues": []}')  # clean scan: only the closure can fail it
    assert main(str(issues), "--shipped", str(tmp_path / "absent.txt")) == 1
    bad = tmp_path / "bad.txt"
    bad.write_text("not a requirement\n")
    assert main(str(issues), "--shipped", str(bad)) == 1
    assert main(str(issues), "--shipped") == 1
    assert "failing closed" in capsys.readouterr().out


def test_main_passes_a_non_shipped_finding_with_the_closure(tmp_path):
    issues = tmp_path / "fossa-issues.json"
    issues.write_text('{"issues": [{"type": "vulnerability", "revisionId": "pip+urllib3$2.6.3"}]}')
    req = tmp_path / "requirements-runtime.txt"
    req.write_text(SHIPPED_TXT)
    assert main(str(issues), "--shipped", str(req)) == 0
    assert main(str(issues)) == 1


def test_the_workflow_passes_the_shipped_closure_to_the_gate():
    wf = (_ROOT / ".github" / "workflows" / "fossa.yml").read_text()
    assert "check_fossa_issues.py fossa-issues.json --shipped requirements-runtime.txt" in wf
