function graphWith(rules: BuilderRule[], defaults: BuilderGraph["defaults"] = { decision: "allow", reason: "d" }): BuilderGraph {
  return { schemaVersion: 1, scope: { kind: "class", agentClass: "t" }, rules, defaults };
}

