// The builder compiler turns a BuilderGraph into a VALID, self-contained rego module: default triple
// always present, every OR-row a partial-set entry sharing its rule's rule_id, the verbatim resolver
// appended unconditionally, no data.*/forbidden-builtin references (nodes have no free-form rego).
// These assert the generated source is deterministic, round-trips its embedded graph blob, respects
// the same 65536-byte / 500-line / 25-regex-op caps the backend's `validate_rego_source` enforces,
// and rejects every malformed-graph shape at compile time (empty rule_id/reason, duplicate rule_id,
// zero conditions, empty keyword/tool list, out-of-range threshold, budget overrun) rather than
// emitting broken/dead rego. The live OPA decision-flip is proven manually (opa check --v0-compatible
// + opa eval against this exact fixture, see the round-A execution report) — a passing compile is not
// proof on its own, same doctrine as the rest of this repo's e2e checks.
