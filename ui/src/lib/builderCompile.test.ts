// ==== Phase 2c: Intent Allowlist mode =============================================================
// A whole-policy DEFAULT-DENY shape (allow only the listed tools, block everything else) — a MODE,
// not another composable condition type, mirroring the server's `norviq/api/threat_intent.py
// generate_intent_rego` (read-only reference) to the shape the builder is allowed to emit: package
// `norviq.intent.<token>` — the documented namespace prefix (docs.norviq.dev/guides/writing-policies/)
// the server generator itself uses, so the server's own governance-classification (coverage.py's
// `_parse_agent_policy`, threats.py's `_governing_policies`) recognizes a builder-authored allowlist —
// and WITHOUT the server's `learned_verbs` feature (server-side registry data this client-side compiler
// has no access to). The live OPA decision-flip (opa check
// --v0-compatible + opa eval + a real kind-cluster POST /policies/evaluate round trip) is proven
// manually, same doctrine as every other fixture in this file — see the Phase 2c execution report.

function allowlistGraph(
  agentClass: string,
  tools: string[],
  refinements: Partial<{ readonly: boolean; egress: boolean; scope: boolean; rate: boolean }> = {}
): BuilderGraph {
  return {
    schemaVersion: 1,
    scope: { kind: "class", agentClass },
    mode: "allowlist",
    rules: [],
    defaults: { decision: "allow", reason: "n/a" },
    allowlist: {
      tools,
      refinements: {
        readonly: !!refinements.readonly,
        egress: !!refinements.egress,
        scope: !!refinements.scope,
        rate: !!refinements.rate
      }
    }
  };
}

